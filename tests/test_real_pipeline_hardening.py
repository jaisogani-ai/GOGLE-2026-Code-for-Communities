def test_model_registry_audit_preservation():
    """Prior registry history must preserve transparent audit corrections and revoke unverified claims."""
    registry = ModelRegistry()
    models = {m["model_id"]: m for m in registry.data.get("models", [])}

    # Verify toy 16-row models are marked revoked
    if "TATHYON-GBC-BASELINE-05755bea" in models:
        m = models["TATHYON-GBC-BASELINE-05755bea"]
        assert m.get("status") == "unverified (revoked)"
        assert m.get("human_approval_documented") is False
        assert "REVOKED" in m.get("audit_correction", "")

    if "TATHYON-GBC-REAL-PILOT-05755bea" in models:
        m = models["TATHYON-GBC-REAL-PILOT-05755bea"]
        assert m.get("status") in ["unverified (revoked)", "candidate"]
        assert m.get("human_approval_documented") is False
        assert m.get("status") != "approved for pilot"

    # Verify simulation benchmark model is marked not approved for pilot
    if "TATHYON-GBC-REAL-PILOT-8229d3e4" in models:
        m = models["TATHYON-GBC-REAL-PILOT-8229d3e4"]
        assert m.get("status") == "benchmark simulation (not approved for pilot)"
