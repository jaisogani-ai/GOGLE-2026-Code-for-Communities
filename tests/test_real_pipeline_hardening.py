def test_spatio_temporal_split_zero_leakage():
    """split_facility_and_time must guarantee ZERO facility overlap and strict temporal ordering."""
    dates = pd.date_range("2026-07-01", "2026-08-30")
    facilities = [f"FAC_{i:02d}" for i in range(10)]
    rows = []
    for fac in facilities:
        for d in dates:
            rows.append({
                "facility_id": fac,
                "date": d,
                "val": 1.0,
            })
    df = pd.DataFrame(rows)

    train_df, test_df, split_def = split_facility_and_time(
        df, test_facility_ratio=0.30, seed=20260928, temporal_split_quantile=0.80
    )

    # 1. Facility mutual exclusivity
    train_facs = set(train_df["facility_id"].unique())
    test_facs = set(test_df["facility_id"].unique())
    assert len(train_facs.intersection(test_facs)) == 0, "Test facilities must NEVER appear in training set"
    assert len(test_facs) == 3
    assert len(train_facs) == 7

    # 2. Temporal boundary
    if split_def.split_timestamp:
        cutoff = pd.Timestamp(split_def.split_timestamp)
        assert (train_df["date"] <= cutoff).all(), "Train set cannot observe records after temporal boundary"


