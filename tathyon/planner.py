# Plan Explorer: Multi-Objective Plan Generation
# --------------------------------------------------------------------------

class PlanExplorer:
    """Generates multiple candidate redistribution plans with different objectives.
    
    The operator sees tradeoffs and chooses. TATHYON does NOT auto-select.
    
    PLAN_A: Closest Donor — minimize total distance
    PLAN_B: Highest Coverage — maximize demand fulfillment
    PLAN_C: Lowest Logistics Cost — minimize ₹
    PLAN_D: Highest Resilience — maximize remaining network buffer
    """

    def __init__(self, graph: HealthcareResourceGraph, store: Optional[EventStore] = None):
        self.graph = graph
        self.store = store or graph.store

    def explore_plans(
        self,
        resource_id: str,
        min_safety_days: float = 14.0,
        max_distance_km: float = 250.0,
        speed_kmph: float = 40.0,
    ) -> dict:
        """Generates 4 candidate plans with different optimization strategies."""
        planner = ResponsePlanner(self.graph, self.store)

        shortages = self.graph.get_shortage_facilities(resource_id)
        donors = self.graph.get_donor_inventory(resource_id, min_safety_days=min_safety_days)

        if not shortages or not donors:
            return {
                "status": "NO_PLANS_POSSIBLE",
                "reason": "No shortages exist or no verified donors available.",
                "shortages_count": len(shortages),
                "donors_count": len(donors),
                "plans": [],
            }

        plans = []

        # PLAN A: Closest Donor (minimize distance)
        plan_a = self._build_plan(
            "PLAN_A_CLOSEST_DONOR",
            "Minimize total transport distance",
            shortages, donors, resource_id,
            sort_key=lambda d, s: self.graph.distance_km(d["facility_id"], s["facility_id"]),
            min_safety_days=min_safety_days,
            max_distance_km=max_distance_km,
            speed_kmph=speed_kmph,
        )
        plans.append(plan_a)

        # PLAN B: Highest Coverage (maximize demand fulfillment)
        plan_b = self._build_plan(
            "PLAN_B_MAX_COVERAGE",
            "Maximize total demand fulfillment across shortage facilities",
            shortages, donors, resource_id,
            sort_key=lambda d, s: -d["surplus_transferable"],  # Largest surplus first
            min_safety_days=min_safety_days,
            max_distance_km=max_distance_km,
            speed_kmph=speed_kmph,
        )
        plans.append(plan_b)

        # PLAN C: Lowest Cost (minimize cost = distance * 25 + handling)
        plan_c = self._build_plan(
            "PLAN_C_LOWEST_COST",
            "Minimize logistics cost (₹25/km + ₹200/transfer)",
            shortages, donors, resource_id,
            sort_key=lambda d, s: self.graph.distance_km(d["facility_id"], s["facility_id"]) * 25.0 + 200.0,
            min_safety_days=min_safety_days,
            max_distance_km=max_distance_km,
            speed_kmph=speed_kmph,
        )
        plans.append(plan_c)

        # PLAN D: Highest Resilience (maximize remaining donor buffer)
        plan_d = self._build_plan(
            "PLAN_D_MAX_RESILIENCE",
            "Maximize remaining network buffer post-redistribution",
            shortages, donors, resource_id,
            sort_key=lambda d, s: -(d["days_of_stock"] - min_safety_days),  # Most buffered donor first
            min_safety_days=min_safety_days,
            max_distance_km=max_distance_km,
            speed_kmph=speed_kmph,
            max_donor_fraction=0.30,  # More conservative extraction
        )
        plans.append(plan_d)

        # Add comparison metrics
        return {
            "status": "PLANS_GENERATED",
            "shortages_count": len(shortages),
            "donors_count": len(donors),
            "resource_id": resource_id,
            "plans": plans,
            "tradeoff_matrix": self._build_tradeoff_matrix(plans),
            "decision_note": (
                "Four candidate plans generated with different optimization objectives. "
                "Examine the tradeoff matrix to understand what each plan sacrifices. "
                "The operator must select based on operational priorities."
            ),
            "provenance": "SIMULATION",
        }

    def _build_plan(
        self,
        plan_name: str,
        objective: str,
        shortages: list[dict],
        donors: list[dict],
        resource_id: str,
        sort_key,
        min_safety_days: float,
        max_distance_km: float,
        speed_kmph: float,
        max_donor_fraction: float = 0.50,
    ) -> dict:
        """Builds a single candidate plan using greedy allocation with given sort key."""
        transfers = []
        used_donor_qty = {d["facility_id"]: 0.0 for d in donors}
        total_covered = 0.0
        total_shortfall = sum(s["shortfall_quantity"] for s in shortages)

        for shortage in sorted(shortages, key=lambda s: s["days_left"]):
            remaining_need = shortage["shortfall_quantity"]
            s_fid = shortage["facility_id"]

            # Rank donors by objective-specific sort key
            ranked_donors = sorted(donors, key=lambda d: sort_key(d, shortage))

            for donor in ranked_donors:
                if remaining_need <= 0:
                    break
                d_fid = donor["facility_id"]
                if d_fid == s_fid:
                    continue

                dist = self.graph.distance_km(d_fid, s_fid)
                if dist > max_distance_km:
                    continue

                available = min(
                    donor["surplus_transferable"] * max_donor_fraction - used_donor_qty.get(d_fid, 0.0),
                    remaining_need,
                )
                if available <= 0:
                    continue

                qty = round(available, 1)
                used_donor_qty[d_fid] = used_donor_qty.get(d_fid, 0.0) + qty
                remaining_need -= qty
                total_covered += qty

                transfers.append({
                    "source": d_fid,
                    "source_name": donor["facility_name"],
                    "destination": s_fid,
                    "destination_name": shortage["facility_name"],
                    "quantity": qty,
                    "distance_km": round(dist, 1),
                    "travel_hours": round(dist / speed_kmph, 1),
                })

        total_distance = sum(t["distance_km"] for t in transfers)
        total_qty = sum(t["quantity"] for t in transfers)
        cost = round(total_distance * 25.0 + len(transfers) * 200.0, 2)
        coverage_pct = round(total_covered / max(total_shortfall, 1.0) * 100, 1)

        # Calculate remaining network buffer
        remaining_buffer_days = []
        for donor in donors:
            d_fid = donor["facility_id"]
            used = used_donor_qty.get(d_fid, 0.0)
            remaining_usable = donor["usable_quantity"] - used
            vel = self.graph.get_resource_state(d_fid, resource_id)
            vel_rate = vel.consumption_velocity if vel else 1.0
            remaining_buffer_days.append(
                round(remaining_usable / max(vel_rate, 0.1), 1)
            )
        avg_remaining_buffer = round(
            sum(remaining_buffer_days) / max(len(remaining_buffer_days), 1), 1
        )

        return {
            "plan_name": plan_name,
            "objective": objective,
            "transfers": transfers,
            "total_quantity": round(total_qty, 1),
            "total_distance_km": round(total_distance, 1),
            "total_cost_inr": cost,
            "coverage_pct": coverage_pct,
            "transfers_count": len(transfers),
            "avg_remaining_donor_buffer_days": avg_remaining_buffer,
            "shortfall_remaining": round(max(total_shortfall - total_covered, 0.0), 1),
        }

    @staticmethod
    def _build_tradeoff_matrix(plans: list[dict]) -> list[dict]:
        """Builds a comparison matrix showing what each plan sacrifices."""
        matrix = []
        for p in plans:
            matrix.append({
                "plan": p["plan_name"],
                "objective": p["objective"],
                "coverage_pct": p["coverage_pct"],
                "distance_km": p["total_distance_km"],
                "cost_inr": p["total_cost_inr"],
                "transfers": p["transfers_count"],
                "remaining_buffer_days": p["avg_remaining_donor_buffer_days"],
                "unmet_shortfall": p["shortfall_remaining"],
            })
        return matrix

